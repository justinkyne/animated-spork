#!/usr/bin/env python3
"""Generates the ad's voiceover with Kokoro TTS (Apache-2.0; runs fully offline).

Writes ../vo.js: every line as an embedded MP3 plus its duration. index.html
schedules the lines on its timeline, so the live page and the rendered MP4s
share one soundtrack. The narrator is a stock synthetic voice, not a clone
of anyone; the quotes are read as quotes.

Setup:
  pip install kokoro-onnx soundfile
  curl -LO https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/kokoro-v1.0.onnx
  curl -LO https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/voices-v1.0.bin
  python3 voiceover/make_vo.py --models <dir with both files> [--ffmpeg /path/to/ffmpeg]
"""
import argparse, base64, json, os, subprocess, tempfile

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

NARRATOR = 'af_heart'
# id: (voice, speed, text)
LINES = {
    'n01': (NARRATOR, 1.0, "Don and Bettina's wedding weekend."),
    'n02': (NARRATOR, 1.0, "A private island."),
    'n03': (NARRATOR, 1.0, "Fireworks over the water."),
    'n04': (NARRATOR, 1.0, "Two nights of parties. Paid for by..."),
    'n05': (NARRATOR, 1.0, "Umar Kremlev. Russian oligarch. Putin ally."),
    'n06': (NARRATOR, 1.05, "Days after traveling with Putin, he bankrolled Don Junior's wedding weekend."),
    'n07': (NARRATOR, 1.05, "A hundred grand a night for the island. About seventy grand in fireworks. Sailor-suit dancers."),
    'n08': (NARRATOR, 1.0, "That's Russian for... paid."),
    'n09': (NARRATOR, 1.05, "One night on that island costs more than the typical American household makes in a year."),
    'n10': (NARRATOR, 1.0, "The fireworks? Two of your weddings. Up in smoke."),
    'n11': (NARRATOR, 1.0, "His spokesperson says Umar is a personal friend of Don."),
    'n12': (NARRATOR, 1.0, "The President says his son told him,"),
    'n13': (NARRATOR, 0.92, "No, I'm paying it back, Dad."),
    'n14': (NARRATOR, 1.0, "Great excuse. Let's all try it."),
    'c1': ('am_michael', 1.0, "I'm paying it back, Dad."),
    'c2': ('af_bella', 1.0, "I'm paying it back, Dad."),
    'c3': ('am_fenrir', 1.0, "I'm paying it back, Dad."),
    'c4': ('af_nicole', 1.0, "I'm paying it back, Dad?"),
    'n15': (NARRATOR, 1.0, "Weird."),
    'n16': (NARRATOR, 1.0, "It only works when Dad's the President."),
    'n17': (NARRATOR, 1.0, "In America, that's called a gift."),
    'n18': (NARRATOR, 1.0, "In Moscow, it's called an investment."),
    'n19': (NARRATOR, 1.0, "A Putin ally picked up their tab."),
    'n20': (NARRATOR, 0.95, "Who's picking up yours?"),
}
PHONEME_FIXES = {'jˈuːmɚ': 'ˈuːmɑːɹ'}  # "Umar" is OO-mar, not YOO-mer


def trim(x, sr, thresh=0.01, pad=0.03):
    idx = np.where(np.abs(x) > thresh)[0]
    if not len(idx):
        return x
    a, b = max(0, idx[0] - int(pad * sr)), min(len(x), idx[-1] + int(pad * sr))
    return x[a:b]


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument('--models', default='.')
    ap.add_argument('--ffmpeg', default=os.environ.get('FFMPEG', 'ffmpeg'))
    ap.add_argument('--out', default=os.path.join(here, '..', 'vo.js'))
    args = ap.parse_args()

    k = Kokoro(os.path.join(args.models, 'kokoro-v1.0.onnx'), os.path.join(args.models, 'voices-v1.0.bin'))
    out = {}
    with tempfile.TemporaryDirectory() as tmp:
        for key, (voice, speed, text) in LINES.items():
            ph = k.tokenizer.phonemize(text, 'en-us')
            for a, b in PHONEME_FIXES.items():
                ph = ph.replace(a, b)
            samples, sr = k.create(ph, voice=voice, speed=speed, is_phonemes=True)
            samples = trim(samples, sr)
            wav, mp3 = os.path.join(tmp, key + '.wav'), os.path.join(tmp, key + '.mp3')
            sf.write(wav, samples, sr)
            subprocess.run([args.ffmpeg, '-loglevel', 'error', '-y', '-i', wav, '-ac', '1', '-ar', '44100',
                            '-c:a', 'libmp3lame', '-b:a', '80k', mp3], check=True)
            with open(mp3, 'rb') as f:
                src = 'data:audio/mpeg;base64,' + base64.b64encode(f.read()).decode()
            out[key] = {'d': round(len(samples) / sr, 3), 'text': text, 'src': src}
            print(f'{key:4} {out[key]["d"]:5.2f}s  {voice:10} {text}')
    with open(args.out, 'w') as f:
        f.write('// Generated by voiceover/make_vo.py (Kokoro TTS). Do not edit by hand.\n')
        f.write('window.VO = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')


if __name__ == '__main__':
    main()
